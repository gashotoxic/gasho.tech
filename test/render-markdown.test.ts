import { test } from "node:test"
import assert from "node:assert/strict"

import { renderMarkdown } from "../lib/studio-api.ts"

/**
 * Regression for review R2: `renderMarkdown` returned the post body unchanged
 * plus markdown substitutions, and callers inject it with
 * `dangerouslySetInnerHTML`. Raw HTML in a post body therefore rendered as live
 * markup — stored XSS a script, image onerror or iframe away from the admin
 * session in localStorage.
 */

test("a <script> payload renders as inert text", () => {
  const html = renderMarkdown('Before\n\n<script>alert(1)</script>\n\nAfter')

  assert.ok(!/<script/i.test(html), `script tag survived: ${html}`)
  assert.ok(html.includes("&lt;script&gt;alert(1)&lt;/script&gt;"), html)
})

test("an img onerror payload cannot execute", () => {
  const html = renderMarkdown('<img src=x onerror="alert(document.cookie)">')

  assert.ok(!/<img/i.test(html), `img tag survived: ${html}`)
  // The handler text may remain, but only as escaped, inert text.
  assert.ok(
    html.includes("&lt;img src=x onerror=&quot;alert(document.cookie)&quot;&gt;"),
    html
  )
  const withoutGenerated = html.replace(/<\/?(h1|h2|h3|strong|em|a|pre|code|td|tr|table|li|ul|br)\b[^>]*>/gi, "")
  assert.ok(!/[<>]/.test(withoutGenerated), `live markup left over: ${withoutGenerated}`)
})

test("raw block markup does not become live DOM", () => {
  const payload = [
    "<div style=\"position:fixed;inset:0\">overlay</div>",
    "<iframe src=\"https://evil.example\"></iframe>",
    "<a href=\"https://evil.example\">phish</a>",
    "<svg/onload=alert(1)>",
  ].join("\n\n")

  const html = renderMarkdown(payload)

  for (const tag of ["<div", "<iframe", "<a ", "<svg"]) {
    assert.ok(!html.includes(tag), `${tag} rendered as markup: ${html}`)
  }
  assert.ok(html.includes("&lt;iframe"), html)
})

test("quotes in the body cannot break out of a generated attribute", () => {
  // The link regex is the only place a body string reaches an attribute value.
  const html = renderMarkdown('[click](https://example.com/"onmouseover="alert(1))')

  assert.ok(!html.includes('"onmouseover="'), `attribute breakout: ${html}`)
  assert.ok(!/\sonmouseover=/.test(html), html)
})

test("javascript: and data: links are dropped, their text kept", () => {
  for (const href of [
    "javascript:alert(1)",
    "JavaScript:alert(1)",
    "data:text/html;base64,PHNjcmlwdD5hbGVydCgxKTwvc2NyaXB0Pg==",
    "vbscript:msgbox(1)",
  ]) {
    const html = renderMarkdown(`[click](${href})`)
    assert.ok(!/href=/i.test(html), `${href} became a link: ${html}`)
    assert.ok(html.includes("click"), html)
  }
})

test("only same-page and named-scheme targets become links", () => {
  const allowed = ["/blogs", "#section", "../other", "./here", "mailto:a@b.c", "tel:+254700000000"]
  for (const href of allowed) {
    assert.ok(/href=/.test(renderMarkdown(`[x](${href})`)), `${href} was rejected`)
  }

  // Protocol-relative targets point at another host without naming a scheme.
  const html = renderMarkdown("[x](//evil.example/login)")
  assert.ok(!/href=/.test(html), `protocol-relative href survived: ${html}`)
})

test("ordinary markdown still renders", () => {
  const html = renderMarkdown(
    [
      "# Title",
      "## Section",
      "**bold** and *italic*",
      "- one",
      "- two",
      "`inline`",
      "| a | b |",
      "[GashoTech](https://gashotech.com)",
    ].join("\n")
  )

  assert.ok(html.includes("<h1>Title</h1>"), html)
  assert.ok(html.includes("<h2>Section</h2>"), html)
  assert.ok(html.includes("<strong>bold</strong>"), html)
  assert.ok(html.includes("<em>italic</em>"), html)
  assert.ok(html.includes("<li>one</li>"), html)
  assert.ok(html.includes("<code>inline</code>"), html)
  assert.ok(html.includes("<td"), html)
  assert.ok(
    html.includes('<a href="https://gashotech.com" target="_blank" rel="noopener noreferrer">GashoTech</a>'),
    html
  )
})

test("every tag in the output was generated by the renderer", () => {
  // Sanity check on the escape-first design: strip the tags this function emits,
  // then no angle bracket from the input may remain.
  const html = renderMarkdown('# Hi\n**bold** `<b>x</b>`')
  const withoutGenerated = html.replace(/<\/?(h1|h2|h3|strong|em|a|pre|code|td|tr|table|li|ul|br)\b[^>]*>/g, "")

  assert.ok(!/[<>]/.test(withoutGenerated), `unescaped markup left over: ${withoutGenerated}`)
})

test("empty input is empty output", () => {
  assert.equal(renderMarkdown(""), "")
})
